const fs = require('fs');
const path = require('path');

const bookPath = path.join(__dirname, '../json_books/كتاب الكيمياء الثالث المتوسط.json');
const book = JSON.parse(fs.readFileSync(bookPath, 'utf8'));

let pagesText = '';
for (let p = 20; p <= 24; p++) {
  if (book.pages[String(p)]) {
    pagesText += `\n[صفحة ${p}]:\n` + book.pages[String(p)].content;
  }
}

const key = process.env.GEMINI_API_KEY || '';
const prompt = `أنت معلم كيمياء عراقي متمرس ومحترف في إعداد الخطط التدريسية لوزارة التربية العراقية.

المطلوب: إعداد خطة درس يومية متكاملة ونوعية ومطابقة بدقة للنصوص والمفردات المستخرجة من الكتاب المنهجي العراقي أدناه.

المادة: الكيمياء
الصف: الثالث المتوسط
نطاق الصفحات: من صفحة 20 إلى 24
طريقة التدريس المختارة: العصف الذهني وحل الأمثلة

نصوص ومفردات صفحات الكتاب المنهجي العراقي المعتمد:
"""
${pagesText}
"""

تعليمات صارمة جداً:
1. استخرج اسم الموضوع العلمي الحقيقي الدقيق من النصوص أعلاه، وممنوع استخدام عبارة "من صفحة 20 إلى 24" في الأهداف أو الشرح أو التقويم.
2. الأهداف السلوكية: 3 أهداف سلوكية مصاغة بدقة (أن + فعل مضارع سلوكي + الطالب + المفهوم العلمي الدقيق مثل الترتيب الإلكتروني، قاعدة هوند، مستويات الطاقة الثانوية).
3. الوسائل: اذكر الوسائل الحقيقية المرتبطة بالدرس (السبورة، الكتاب، مخطط مستويات الطاقة والأوربيتالات).
4. التمهيد: سؤال تحفيزي ذكي حول عدد الإلكترونات وكيفية توزيعها حول النواة.
5. العرض: شرح مفصل لخطوات التوزيع الإلكتروني وقواعد أوفباو وهوند مع حل الأمثلة المذكورة في الصفحات (مثل ذرة الهيدروجين، الهيليوم، الليثيوم، البريليوم، الصوديوم).
6. التقويم: 3 أسئلة تقويمية تطبيقية تطلب من الطالب كتابة التوزيع الإلكتروني لذرات محددة.
7. الواجب البيتي: حل التمارين المذكورة في الصفحات (تمرين 1-6).

التزم بالعناوين التالية بالضبط:
الأهداف السلوكية
الوسائل
التمهيد
العرض
التقويم
الواجب البيتي
`;

async function main() {
  const response = await fetch('https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'X-goog-api-key': key },
    body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }] })
  });

  const data = await response.json();
  console.log('=== RESULT FROM GEMINI ===');
  console.log(data.candidates[0].content.parts[0].text);
}

main().catch(console.error);

